export const cardProducts: CardProductContent[] = productItems.map((item) => {
  const override = cardProductOverrides[item.id];

  if (!override) {
    const gallery = imageSets[item.category].map((src, index) => ({
      id: `gallery-${index + 1}`,
      src,
      alt: `${item.name} — изображение ${index + 1}`,
    }));

    return {
      id: item.id,
      article: `CAT-${item.id.toUpperCase()}`,
      title: item.name,
      categoryLabel: item.categoryLabel,
      lead: item.description,
      description: [item.description],
      specs: [
        { label: 'Тип', value: item.type },
        { label: 'Назначение', value: item.application },
      ],
      gallery,
      statuses: [{ id: 'delivery', label: 'Доставка по РФ' }],
    };
  }

  return {
    id: item.id,
    title: item.name,
    categoryLabel: item.categoryLabel,
    ...override,
  };
});

export const cardProductsById = Object.fromEntries(cardProducts.map((item) => [item.id, item])) as Record<
  string,
  CardProductContent
>;
